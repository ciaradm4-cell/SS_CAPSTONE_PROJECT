def acm2skyimage(acm, xpos, ypos, freq, lo, m):
#
# conversion of ACM to sky image
#
# arguments
# acm    : nelem x nelem x nchannel array correlation matrix
# xpos   : x-position of antennas (vector of length nelem)
# ypos   : y-position of antennas (vector of length nelem)
# freq   : frequencies in Hz (vector of length nchannel)
# l, m   : l and m points to which to direct the array (vectors)
#
# return value
# skymap : length(l) x length(m) x nchannel matrix containing the
#          resulting sky maps
#
# SJW, 2004
#
# modified April 19, 2005 by SJW: correct coordinate conventions
# modified July 20, 2006 by SJW: optimization for release in LOFAR package

  [nelem, dummy] = np.shape(acm)
  nchannel = 1 #(its always one)
  c  = 2.9979245e8

  skymap = np.zeros((len(l), len(m)))#, nchannel)

  for nch in range (0, nchannel):
    print ('acm2skyimage: working on channel ' + str(nch+1) + ' of ' + str(nchannel))
    wavelength = c / freq #(nch)
    k = (2 * np.pi) / wavelength
    wx = np.exp(-1j * k * xpos[:] * lo)#.')
    wy = np.exp(-1j * k * ypos[:] * m)#.')
    #wz = exp(-i * k * zpos(:) * (sqrt (1 - l(:).^2 - m(:).^2)).')
    for lidx in range ( 0, len(l)):
      for midx in range ( 0, len(m)):
        weight = np.multiply(wx[:, lidx], wy[:, midx]) # .* wz(:,midx);
        skymap[lidx,midx] = np.real(np.real(np.matrix(weight).H * np.matrix(acm[:, :]) * np.matrix(weight) ))[0,0]
  return skymap

