def CalcFreq(rcumode, subband):
    if rcumode == 5:
        freqoff = 100e6;
        basefreq = 200.0;
    elif rcumode == 6:
        freqoff = 160e6;
        basefreq = 160.0;
    elif rcumode == 7:
        freqoff = 200e6;
        basefreq = 200.0;
    else:
        freqoff = 0;
        basefreq = 200.0;
    frequency = ((basefreq / 1024 ) * subband + (freqoff/1e6))
    return frequency, freqoff

def readCalTable(calfile):

  # [calx, caly, header] = readCalTable(calfile)
  #
  # Read calibration table from a properly formatted calibration table file.
  #
  # Argument
  # calfile : file name of calibration table file
  #
  # Return values
  # calx   : Nelem x Nsb (48 x 512 for Dutch stations, 96 x 512 for European
  #          stations) matrix containing a complex valued correction factor
  #          for each element and each subband for the array of x-elements.
  # caly   : corresponding result for the array of y-elements.
  # header : header of calibration table
  #
  # SJW, 18 October 2011
  # modified by SJW on 3 February 2012 (header in calibration tables)
  # modified by ME on 27 February 2012 (according to latest header
  # definitions.
  # N.B. this version is able to read CalTables with or with no headers.

  # get file descriptor
  fid = open(calfile, 'rb')
  # distinguish between CalTable files with or without headers; newer
  # CalTable files should contain headers
  header = bytearray()

  newline = fid.readline()

  if b'HeaderStart' in newline:
      position_indicator=fid.tell()
      newline = fid.readline()
      fid.seek(position_indicator)
      while b'HeaderStop' not in newline:
           curchar = fid.read(1)
           print( str(curchar))
           header.extend(curchar)#+=curchar
           if curchar == b'\n' or curchar == b'\r':
               position_indicator=fid.tell()
               newline = fid.readline()
               fid.seek(position_indicator)
      newline = fid.readline()                    # dummy value
  else:
      fid.seek(0)                          # set position descriptor to beginning of file
  # read CalTable
  position_indicator=fid.tell()
  fid.seek(position_indicator)
  data = np.fromfile(fid, dtype=np.float64)
  fid.close()
  Nrcu = len(data) / (2 * 512)
  comp=data[0::2] + 1j * data[1::2]
  cal = np.reshape(comp, (int(Nrcu), 512), order='F') 
  caly = cal[1::2]
  return calx, caly, header

